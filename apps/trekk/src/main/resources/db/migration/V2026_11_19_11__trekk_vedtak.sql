SET lock_timeout = '5s';

CREATE TABLE trekkvedtak
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME trekk_vedtak_id_seq) PRIMARY KEY NOT NULL,
    ekstern_trekk_id BIGINT,
    trekktype TEXT NOT NULL,
    kreditor_tss_id TEXT,
    kreditor_trekk_id TEXT,
    kreditor_ref TEXT,
    belop_saldo NUMERIC(11,2),
    kreditor_kid TEXT,
    gyldig_tom DATE,
    ansv_enhet TEXT NOT NULL,
    debitor_id TEXT NOT NULL, -- fnr midlertidig
    dato_pri_fom DATE,
    kilde TEXT,
    trekkstatus TEXT NOT NULL,
    bruker TEXT NOT NULL,
    tidspkt_reg TIMESTAMPTZ NOT NULL,
    mottatt TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE trekkvedtak_historikk
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
    trekkvedtak TEXT NOT NULL,
    tidspkt_reg TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE trekkperiode
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME trekk_periode_id_seq) PRIMARY KEY NOT NULL,
    trekkvedtak_id BIGINT NOT NULL,
    dato_fom DATE NOT NULL,
    dato_tom DATE,
    sats NUMERIC(11,2) NOT NULL,
    satstype TEXT NOT NULL,
    feil_reg BOOLEAN NOT NULL DEFAULT false,
    bruker TEXT NOT NULL,
    tidspkt_reg TIMESTAMPTZ NOT NULL,
    CONSTRAINT trekkperiode_trekkvedtak_id_fkey FOREIGN KEY (trekkvedtak_id) REFERENCES trekkvedtak (id)
);

CREATE TABLE trekk_i_fagomraade
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
    trekkvedtak_id BIGINT NOT NULL,
    fagomraade_kode TEXT NOT NULL,
    aktiv BOOLEAN NOT NULL,
    tidspkt_reg TIMESTAMPTZ NOT NULL,
    CONSTRAINT trekk_i_fagomraade_trekkvedtak_id_fkey FOREIGN KEY (trekkvedtak_id) REFERENCES trekkvedtak (id)
);

CREATE INDEX trekkvedtak_trekktype_idx ON trekkvedtak (trekktype);
CREATE INDEX trekkvedtak_debitor_id ON trekkvedtak (debitor_id);
CREATE INDEX trekkvedtak_debitor_mottatt_idx ON trekkvedtak (debitor_id, mottatt DESC, id DESC);
CREATE INDEX trekkvedtak_ekstern_trekk_id ON trekkvedtak (ekstern_trekk_id);
CREATE INDEX trekkvedtak_mottatt_id_desc_idx ON trekkvedtak (mottatt DESC, id DESC);
CREATE INDEX trekkperiode_trekkvedtak_id ON trekkperiode (trekkvedtak_id);
CREATE INDEX trekk_i_fagomraade_trekkvedtak_id_idx ON trekk_i_fagomraade (trekkvedtak_id);
